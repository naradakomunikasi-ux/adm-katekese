import assert from 'node:assert/strict';
import fs from 'node:fs';
import { isIdle, touchSession, sessionSecurityState, DEFAULT_IDLE_TIMEOUT_MS } from './src/auth.js';
const now=Date.parse('2026-08-11T13:00:00Z');
const storage={value:null,setItem(_k,v){this.value=v;},getItem(){return this.value;},removeItem(){this.value=null;}};
const session={token:'t',user:{role:'ADMIN_KATEKESE'},expiresAt:'2026-08-11T15:00:00Z',lastActivityAt:now-1000};
assert.equal(isIdle(session,now),false);
assert.equal(isIdle({...session,lastActivityAt:now-DEFAULT_IDLE_TIMEOUT_MS-1},now),true);
assert.equal(sessionSecurityState({...session,lastActivityAt:now-DEFAULT_IDLE_TIMEOUT_MS-1},now),'idle');
const touched=touchSession(session,now,storage);
assert.equal(touched.lastActivityAt,now);
assert.ok(storage.value.includes(String(now)));
const app=fs.readFileSync(new URL('./src/App.jsx',import.meta.url),'utf8');
assert.match(app,/Sesi berakhir karena tidak ada aktivitas selama 30 menit/);
assert.match(app,/online/);
assert.match(app,/offlineBanner/);
const authSource=fs.readFileSync(new URL('./src/auth.js',import.meta.url),'utf8');
assert.match(authSource,/globalThis\.sessionStorage/);
assert.doesNotMatch(authSource,/globalThis\.localStorage/);
console.log('Session security/offline contract: 10/10 PASS');
