import fs from 'node:fs';
import assert from 'node:assert/strict';
const version = fs.readFileSync('VERSION','utf8').trim();
const frontend = JSON.parse(fs.readFileSync('frontend/package.json','utf8')).version;
const backend = JSON.parse(fs.readFileSync('backend/package.json','utf8')).version;
const versionSource = fs.readFileSync('backend/src/version.js','utf8');
const defaultMatch = versionSource.match(/APP_VERSION\s*=\s*process\.env\.APP_VERSION\s*\|\|\s*'([^']+)'/);
assert.ok(defaultMatch, 'backend version source must declare APP_VERSION default');
const envExample=fs.readFileSync('.env.example','utf8').match(/^APP_VERSION=(.+)$/m)?.[1]?.trim();
const compose=fs.readFileSync('docker-compose.yml','utf8');
const composeMatch=compose.match(/APP_VERSION:\s*\$\{APP_VERSION:-([^}]+)\}/);
assert.ok(composeMatch, 'docker-compose APP_VERSION fallback must exist');
assert.ok(version, 'VERSION must not be empty');
assert.equal(frontend, version, `frontend version ${frontend} != root VERSION ${version}`);
assert.equal(backend, version, `backend version ${backend} != root VERSION ${version}`);
assert.equal(defaultMatch[1], version, `backend runtime default ${defaultMatch[1]} != root VERSION ${version}`);
assert.equal(envExample, version, `.env.example APP_VERSION ${envExample} != root VERSION ${version}`);
assert.equal(composeMatch[1].trim(), version, `docker-compose APP_VERSION ${composeMatch[1].trim()} != root VERSION ${version}`);
console.log(JSON.stringify({status:'PASS',version,targets:['VERSION','frontend/package.json','backend/package.json','backend/src/version.js','.env.example','docker-compose.yml']},null,2));
